import { mkdirSync, writeFileSync, readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("../", import.meta.url));
const source = process.argv.find((a) => a.startsWith("--source="))?.slice(9);
if (!source) throw Error("需要 --source=<workflow-zjt>");
const extension = "service/worker/readFile/extension/";
const documents = Object.fromEntries(
  Object.entries({
    parseTxt: "rawText",
    parseMarkdown: "rawText",
    parseCsv: "csv",
    parseHtml: "html",
    parsePdf: "pdf",
    parseDocx: "docx",
    parsePptx: "pptx",
    parseXlsx: "xlsx",
  }).map(([name, file]) => [name, extension + file + ".ts"]),
);
const entries = {
  ...documents,
  parsePdfCustom: "service/common/file/read/utils.ts",
  parsePdfTextIn: "service/thirdProvider/textin/index.ts",
  parsePdfDoc2x: "service/thirdProvider/doc2x/index.ts",
  parseFile: "service/common/file/read/utils.ts",
  htmlToMarkdown: "service/worker/htmlStr2Md/utils.ts",
  textToChunks: "global/common/string/textSplitter.ts",
  previewFileChunks: "global/common/string/textSplitter.ts",
  readFiles: "service/core/workflow/dispatch/tools/readFiles.ts",
  moderateText: "service/core/chat/postTextCensor.ts",
  listAuditLogs: "service/support/user/audit/schema.ts",
  ...Object.fromEntries(
    ["modelChat", "modelEmbed", "modelRerank", "modelTts", "modelStt"].map(
      (n) => [n, "service/core/ai/config.ts"],
    ),
  ),
};
const manifest = [];
for (const [name, file] of Object.entries(entries)) {
  const route = "/api/workflow/nodes/" + name;
  const folder = path.join(root, "src/app", route);
  mkdirSync(folder, { recursive: true });
  writeFileSync(
    path.join(folder, "route.ts"),
    '// Generated by scripts/capability-routes.mjs\nimport {capabilityRoute} from "@/server/capabilities/http";\nexport const runtime = "nodejs";\nexport const POST = capabilityRoute("' +
      name +
      '");\n',
  );
  const sha256 = createHash("sha256")
    .update(readFileSync(path.join(source, "fastify/vendor", file)))
    .digest("hex");
  manifest.push({ name, route, reference: file, sha256 });
}
writeFileSync(
  path.join(root, "src/server/capabilities/manifest.json"),
  JSON.stringify(manifest, null, 2) + "\n",
);
